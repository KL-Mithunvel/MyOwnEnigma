"""Generate the Verilog headers in rtl/ from config.yaml and tools/enigma_ref.py.

    python tools/gen_tables.py

Writes:
  rtl/enigma_params.vh   `define macros (timing in clock ticks, column count, ...)  - file scope
  rtl/enigma_tables.vh   functions: rotor/reflector ROMs, keyboard decode, lamp encode - module scope
  rtl/enigma_presets.vh  always @* block selecting a machine preset                    - module scope

The wiring data comes from enigma_ref.py so the model and the hardware cannot drift apart.
Generated files must never be edited by hand.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import enigma_ref as ref  # noqa: E402

BANNER = "// GENERATED by tools/gen_tables.py from config.yaml and enigma_ref.py - DO NOT EDIT BY HAND.\n"
MAX_PRESETS = 4  # selected by sw[1:0]


def load_config() -> dict:
    return yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))


def pack5(values: list[int]) -> int:
    """Pack 5-bit values, entry k at bits [5k+4:5k]."""
    word = 0
    for k, v in enumerate(values):
        word |= v << (5 * k)
    return word


def rom_function(name: str, selector_bits: int, tables: list[list[int]]) -> str:
    """A function returning table[sel][idx]; table words are 26 x 5 = 130 bits."""
    lines = [
        f"    function [4:0] {name};",
        f"        input [{selector_bits - 1}:0] sel;",
        "        input [4:0] idx;",
        "        reg [129:0] w;",
        "        begin",
        "            case (sel)",
    ]
    for sel, table in enumerate(tables):
        lines.append(f"                {selector_bits}'d{sel}: w = 130'h{pack5(table):033x};")
    lines.append(f"                default: w = 130'h{pack5(tables[0]):033x};  // out-of-range select -> first entry")
    lines += ["            endcase", f"            {name} = w[idx*5 +: 5];", "        end", "    endfunction", ""]
    return "\n".join(lines)


def build_params(cfg: dict) -> str:
    hz = cfg["board"]["clock_hz"]
    t = cfg["timing"]
    columns = cfg["keyboard"]["columns"]
    max_col = max(int(p[:4], 2) for p in cfg["keyboard"]["keys"].values())
    if max_col >= columns:
        raise SystemExit(f"keyboard.columns={columns} but a key uses column {max_col}")
    scan_ticks = hz * t["scan_dwell_us"] // 1_000_000
    macros = {
        "CFG_CLOCK_HZ": hz,
        "CFG_SCAN_TICKS": scan_ticks,
        "CFG_NUM_COLS": columns,
        "CFG_DEBOUNCE_FRAMES": t["debounce_frames"],
        "CFG_LAMP_MIN_ON_TICKS": hz * t["lamp_min_on_ms"] // 1000,
        "CFG_BTN_DEBOUNCE_TICKS": hz * t["button_debounce_ms"] // 1000,
        "CFG_HEARTBEAT_TICKS": hz // (2 * t["heartbeat_hz"]),
        "CFG_LAMP_IDLE_CODE": f"5'd{cfg['lamp']['idle_code']}",
        "CFG_NUM_PRESETS": len(cfg["presets"]),
    }
    out = [BANNER, "`ifndef ENIGMA_PARAMS_VH", "`define ENIGMA_PARAMS_VH", ""]
    out += [f"`define {k} {v}" for k, v in macros.items()]
    out += ["", "`endif", ""]
    return "\n".join(out)


def build_tables(cfg: dict) -> str:
    out = [BANNER, "// Included inside a module body.", ""]

    # --- rotor / reflector ROMs -------------------------------------------------
    fwd = [[ref.to_int(c) for c in ref.ROTORS[name][0]] for name in ref.ROTOR_NAMES]
    inv = [[w.index(k) for k in range(ref.N)] for w in fwd]
    out.append("    // Rotor wiring, entry contact -> exit contact. sel: I=0 II=1 III=2 IV=3 V=4")
    out.append(rom_function("rotor_fwd", 3, fwd))
    out.append("    // Inverse rotor wiring (signal returning from the reflector)")
    out.append(rom_function("rotor_inv", 3, inv))
    notches = [ref.to_int(ref.ROTORS[name][1]) for name in ref.ROTOR_NAMES]
    out += ["    // Turnover notch (window letter) of each rotor", "    function [4:0] rotor_notch;",
            "        input [2:0] sel;", "        begin", "            case (sel)"]
    out += [f"                3'd{i}: rotor_notch = 5'd{n};  // {ref.ROTOR_NAMES[i]}" for i, n in enumerate(notches)]
    out += [f"                default: rotor_notch = 5'd{notches[0]};", "            endcase", "        end", "    endfunction", ""]
    refl = [[ref.to_int(c) for c in ref.REFLECTORS[name]] for name in ref.REFLECTOR_NAMES]
    out.append("    // Reflector. sel: B=0 C=1")
    out.append(rom_function("reflect", 1, refl))

    # --- keyboard decode / encode --------------------------------------------------
    keys = {ref.to_int(k): v for k, v in cfg["keyboard"]["keys"].items()}
    if len(keys) != 26 or len(set(keys.values())) != 26:
        raise SystemExit("keyboard.keys must define 26 distinct patterns for A-Z")
    out += ["    // Keyboard: {column[3:0], rows[3:0]} -> letter code, 31 = no/unknown key",
            "    function [4:0] key_decode;", "        input [7:0] pat;", "        begin", "            case (pat)"]
    out += [f"                8'b{v[:4]}_{v[4:]}: key_decode = 5'd{k};  // {ref.to_letter(k)}" for k, v in sorted(keys.items())]
    out += ["                default: key_decode = 5'd31;", "            endcase", "        end", "    endfunction", ""]
    out += ["    // Keyboard: letter code -> {column[3:0], rows[3:0]} (used by testbenches' keyboard model)",
            "    function [7:0] key_pattern;", "        input [4:0] letter;", "        begin", "            case (letter)"]
    out += [f"                5'd{k}: key_pattern = 8'b{v[:4]}_{v[4:]};" for k, v in sorted(keys.items())]
    out += ["                default: key_pattern = 8'b0;", "            endcase", "        end", "    endfunction", ""]

    codes = {ref.to_int(k): v for k, v in cfg["lamp"]["codes"].items()}
    if len(codes) != 26 or len(set(codes.values())) != 26 or cfg["lamp"]["idle_code"] in codes.values():
        raise SystemExit("lamp.codes must be 26 distinct codes, none equal to idle_code")
    out += ["    // Lamp board: letter code -> 5-bit 4067 code", "    function [4:0] lamp_encode;",
            "        input [4:0] letter;", "        begin", "            case (letter)"]
    out += [f"                5'd{k}: lamp_encode = 5'd{v};  // {ref.to_letter(k)}" for k, v in sorted(codes.items())]
    out += [f"                default: lamp_encode = 5'd{cfg['lamp']['idle_code']};", "            endcase", "        end",
            "    endfunction", ""]
    return "\n".join(out)


def build_presets(cfg: dict) -> str:
    presets = cfg["presets"]
    if not 1 <= len(presets) <= MAX_PRESETS:
        raise SystemExit(f"need 1..{MAX_PRESETS} presets, got {len(presets)}")
    out = [BANNER, "// Included inside a module body that declares: preset_idx[1:0] and regs",
           "// rotor_sel[8:0], ring_set[14:0], reflector_sel, plug_en[9:0], plug_a[49:0], plug_b[49:0].", "",
           "    always @* begin", "        case (preset_idx)"]
    def body(p: dict) -> list[str]:
        rotors = [ref.ROTOR_NAMES.index(r) for r in p["rotors"]]
        rings = [ref.to_int(c) for c in p["rings"]]
        pairs = ref.parse_plugs(p["plugs"])
        en = sum(1 << k for k in range(len(pairs)))
        pa = pack5([a for a, _ in pairs])
        pb = pack5([b for _, b in pairs])
        return [
            f"                rotor_sel = {{3'd{rotors[0]}, 3'd{rotors[1]}, 3'd{rotors[2]}}};",
            f"                ring_set = {{5'd{rings[0]}, 5'd{rings[1]}, 5'd{rings[2]}}};",
            f"                reflector_sel = 1'd{ref.REFLECTOR_NAMES.index(p['reflector'])};",
            f"                plug_en = 10'h{en:03x};",
            f"                plug_a = 50'h{pa:013x};",
            f"                plug_b = 50'h{pb:013x};",
        ]

    for i, p in enumerate(presets):
        out += [f"            2'd{i}: begin  // {p['name']}"] + body(p) + ["            end"]
    out += ["            default: begin  // unused preset codes fall back to preset 0"] + body(presets[0]) + [
        "            end", "        endcase", "    end", ""]
    return "\n".join(out)


def main() -> None:
    cfg = load_config()
    outputs = {
        "rtl/enigma_params.vh": build_params(cfg),
        "rtl/enigma_tables.vh": build_tables(cfg),
        "rtl/enigma_presets.vh": build_presets(cfg),
    }
    for rel, text in outputs.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {rel} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
